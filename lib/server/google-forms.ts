import "server-only";
import type { GeneratedLessonPlan } from "@/lib/planning";

type OAuthClient = { client_id?: string; client_secret?: string };

function oauthSettings() {
  const credentialsText = process.env.GOOGLE_FORMS_CREDENTIALS_JSON;
  const tokenText = process.env.GOOGLE_FORMS_TOKEN_JSON;
  if (!credentialsText || !tokenText) throw new Error("Google Forms OAuth is not configured.");
  const credentials = JSON.parse(credentialsText) as { installed?: OAuthClient; web?: OAuthClient };
  const token = JSON.parse(tokenText) as { refresh_token?: string };
  const client = credentials.installed || credentials.web;
  if (!client?.client_id || !client.client_secret || !token.refresh_token) {
    throw new Error("Google Forms OAuth credentials are incomplete.");
  }
  return { clientId: client.client_id, clientSecret: client.client_secret, refreshToken: token.refresh_token };
}

async function accessToken() {
  const oauth = oauthSettings();
  const response = await fetch("https://oauth2.googleapis.com/token", {
    method: "POST",
    headers: { "content-type": "application/x-www-form-urlencoded" },
    body: new URLSearchParams({
      client_id: oauth.clientId,
      client_secret: oauth.clientSecret,
      refresh_token: oauth.refreshToken,
      grant_type: "refresh_token",
    }),
    cache: "no-store",
  });
  const payload = await response.json() as { access_token?: string; error_description?: string };
  if (!response.ok || !payload.access_token) throw new Error(payload.error_description || "Google Forms authorization failed.");
  return payload.access_token;
}

async function formsFetch(path: string, token: string, init: RequestInit) {
  const response = await fetch(`https://forms.googleapis.com/v1/${path}`, {
    ...init,
    headers: { authorization: `Bearer ${token}`, "content-type": "application/json", ...(init.headers || {}) },
    cache: "no-store",
  });
  const payload = await response.json().catch(() => ({})) as Record<string, unknown>;
  if (!response.ok) {
    const apiError = payload.error as { message?: string } | undefined;
    throw new Error(apiError?.message || `Google Forms request failed (${response.status}).`);
  }
  return payload;
}

export async function createLessonQuiz(lesson: GeneratedLessonPlan) {
  const token = await accessToken();
  const created = await formsFetch("forms", token, {
    method: "POST",
    body: JSON.stringify({ info: { title: `ChalkEvo | ${lesson.className} | ${lesson.title}`, documentTitle: `ChalkEvo | ${lesson.className} | ${lesson.title}` } }),
  });
  const formId = String(created.formId || "");
  if (!formId) throw new Error("Google Forms did not return a form ID.");
  const requests: Record<string, unknown>[] = [
    { updateSettings: { settings: { quizSettings: { isQuiz: true } }, updateMask: "quizSettings.isQuiz" } },
    { updateFormInfo: { info: { description: `${lesson.objective}\n\nGenerated by ChalkEvo with Gemini. Review before sharing.` }, updateMask: "description" } },
    { createItem: { item: { title: "Student name", questionItem: { question: { required: true, textQuestion: { paragraph: false } } } }, location: { index: 0 } } },
  ];
  lesson.quiz.forEach((question, index) => requests.push({
    createItem: {
      item: {
        title: question.prompt,
        description: question.explanation,
        questionItem: { question: {
          required: true,
          grading: { pointValue: 1, correctAnswers: { answers: [{ value: question.options[question.answerIndex] }] } },
          choiceQuestion: { type: "RADIO", options: question.options.map((value) => ({ value })), shuffle: false },
        } },
      },
      location: { index: index + 1 },
    },
  }));
  await formsFetch(`forms/${formId}:batchUpdate`, token, { method: "POST", body: JSON.stringify({ includeFormInResponse: true, requests }) });
  try {
    await formsFetch(`forms/${formId}:setPublishSettings`, token, {
      method: "POST",
      body: JSON.stringify({ publishSettings: { publishState: { isPublished: true, isAcceptingResponses: true } } }),
    });
  } catch (error) {
    console.warn("Form publish settings unchanged", error instanceof Error ? error.message : "Unknown error");
  }
  const finalForm = await formsFetch(`forms/${formId}`, token, { method: "GET" });
  return {
    formId,
    editUrl: `https://docs.google.com/forms/d/${formId}/edit`,
    responderUri: String(finalForm.responderUri || `https://docs.google.com/forms/d/${formId}/viewform`),
    questionCount: lesson.quiz.length,
  };
}
